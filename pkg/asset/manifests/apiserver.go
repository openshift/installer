package manifests

import (
	"context"
	"fmt"
	"path"

	metav1 "k8s.io/apimachinery/pkg/apis/meta/v1"
	"sigs.k8s.io/yaml"

	configv1 "github.com/openshift/api/config/v1"
	"github.com/openshift/installer/pkg/asset"
	"github.com/openshift/installer/pkg/asset/installconfig"
)

// APIServerCfgFilename is the path to the generated APIServer config manifest.
var APIServerCfgFilename = path.Join(manifestDir, "cluster-apiserver-02-config.yml")

// APIServer generates the cluster APIServer config manifest, which sets the
// cluster-wide TLS security profile and adherence policy.
type APIServer struct {
	FileList []*asset.File
}

var _ asset.WritableAsset = (*APIServer)(nil)

// Name returns a human friendly name for the asset.
func (*APIServer) Name() string {
	return "APIServer Config"
}

// Dependencies returns the assets needed to generate the APIServer config.
func (*APIServer) Dependencies() []asset.Asset {
	return []asset.Asset{
		&installconfig.InstallConfig{},
	}
}

// Generate renders the APIServer config, selecting the TLS security profile
// from the install config and defaulting to Modern when none is set.
func (a *APIServer) Generate(_ context.Context, parents asset.Parents) error {
	install := &installconfig.InstallConfig{}
	parents.Get(install)

	config := &configv1.APIServer{
		TypeMeta: metav1.TypeMeta{
			APIVersion: configv1.SchemeGroupVersion.String(),
			Kind:       "APIServer",
		},
		ObjectMeta: metav1.ObjectMeta{
			Name: "cluster",
		},
		Spec: configv1.APIServerSpec{
			TLSAdherence: configv1.TLSAdherencePolicyStrictAllComponents,
		},
	}

	switch configv1.TLSProfileType(install.Config.TLSProfileType) {
	case "", configv1.TLSProfileModernType:
		config.Spec.TLSSecurityProfile = &configv1.TLSSecurityProfile{
			Type:   configv1.TLSProfileModernType,
			Modern: &configv1.ModernTLSProfile{},
		}
	case configv1.TLSProfileIntermediateType:
		config.Spec.TLSSecurityProfile = &configv1.TLSSecurityProfile{
			Type:         configv1.TLSProfileIntermediateType,
			Intermediate: &configv1.IntermediateTLSProfile{},
		}
	case configv1.TLSProfileOldType:
		config.Spec.TLSSecurityProfile = &configv1.TLSSecurityProfile{
			Type: configv1.TLSProfileOldType,
			Old:  &configv1.OldTLSProfile{},
		}
	default:
		return fmt.Errorf("unsupported TLS profile type %q", install.Config.TLSProfileType)
	}

	configData, err := yaml.Marshal(config)
	if err != nil {
		return fmt.Errorf("failed to create %s manifests from APIServer: %w", a.Name(), err)
	}

	a.FileList = []*asset.File{
		{
			Filename: APIServerCfgFilename,
			Data:     configData,
		},
	}

	return nil
}

// Files returns the files generated by the asset.
func (a *APIServer) Files() []*asset.File {
	return a.FileList
}

// Load returns false since this asset is always generated and never loaded
// from disk.
func (a *APIServer) Load(f asset.FileFetcher) (bool, error) {
	return false, nil
}
